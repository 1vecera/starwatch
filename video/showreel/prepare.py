"""Stage the reel's inputs under public/showreel/ from the captures, the brand files and the audio.

Run from video/ after `npm run capture` has written tmp/captures/:

    uv run showreel/prepare.py --audio ../../tmp/showreel/audio

Captures are copied unchanged. The score is ElevenLabs take 4, cut to start 3.762 s in (two bars of
its intro) and kept as WAV; the effects are ElevenLabs takes from the Mluva showreel's sessions.
"""

import argparse
import hashlib
import json
import re
import shutil
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
REPO = ROOT.parent
CAPTURES = ROOT / "tmp/captures"
OUT = ROOT / "public/showreel"
TAKES = ["atlas", "tiles", "parts", "spotlight", "pulse", "radar", "results", "phone"]
BRAND = ["lockup.svg", "icon-spotlight.svg", "icon-pulse.svg", "icon-radar.svg", "icon-data.svg"]
IMG = ["bg-topo.svg", "bg-grid.svg", "mark-3d.webp"]
SCORE = ("score-4.mp3", 3.762)
SFX = {
    "impact": "massive-cinematic-sub-bass_k2oyp.mp3",
    "impact-long": "massive-cinematic-sub-bass_VRBuW.mp3",
    "whoosh-soft": "fast-airy-whoosh_hk3nd.mp3",
    "whoosh": "fast-airy-whoosh_8m4uS.mp3",
    "pop": "bright-flash-pop_2eU6P.mp3",
    "pop-2": "bright-flash-pop_ANJFv.mp3",
    "flap": "split-flap-departure-board_jKBU2.mp3",
    "thud": "single-deep-mechanical_qDf6b.mp3",
    "jelly": "soft-glossy-jelly_jdBPe.mp3",
    "tick": "tiny-soft-ui_A0IpI.mp3",
    "riser": "tense-white-noise-riser_Flztt.mp3",
}


def main() -> None:
    """Copy captures, brand files and audio into public/showreel and record their hashes."""
    parser = argparse.ArgumentParser()
    parser.add_argument("--audio", type=Path, required=True, help="Folder with score-4.mp3 and sfx/")
    args = parser.parse_args()
    OUT.mkdir(parents=True, exist_ok=True)
    for stale in OUT.iterdir():
        if stale.is_dir() and stale.name not in {*TAKES, "brand", "img", "audio"}:
            shutil.rmtree(stale)
    for take in TAKES:
        shutil.rmtree(OUT / take, ignore_errors=True)
        shutil.copytree(CAPTURES / take, OUT / take)
    (OUT / "brand").mkdir(exist_ok=True)
    for name in BRAND:
        shutil.copy2(REPO / "app/web/brand" / name, OUT / "brand" / name)
    (OUT / "img").mkdir(exist_ok=True)
    for name in IMG:
        shutil.copy2(REPO / "app/web/img" / name, OUT / "img" / name)
    audio = OUT / "audio"
    audio.mkdir(exist_ok=True)
    name, start = SCORE
    subprocess.run(
        ["ffmpeg", "-v", "error", "-y", "-ss", f"{start:.3f}", "-i", str(args.audio / name), "-t", "46",
         "-ar", "48000", "-c:a", "pcm_s24le", str(audio / "score.wav")],
        check=True,
    )  # fmt: skip
    for key, file in SFX.items():
        shutil.copy2(args.audio / "sfx" / file, audio / f"{key}.mp3")
    topo(REPO / "app/web/img/bg-topo.svg", ROOT / "src/showreel/parts/topo.ts")
    manifest = {
        str(path.relative_to(OUT)): hashlib.sha256(path.read_bytes()).hexdigest()
        for path in sorted(OUT.rglob("*"))
        if path.is_file() and path.name != "media.json"
    }
    (OUT / "media.json").write_text(json.dumps(manifest, indent=2))
    print(f"Staged {len(manifest)} files in {OUT}")


def topo(svg: Path, out: Path) -> None:
    """Split the app's contour background into single contours, so the reel can draw them on one by one."""
    text = svg.read_text()
    layers = []
    for match in re.finditer(r'<path d="([^"]+)" stroke="([^"]+)" stroke-opacity="([^"]+)" stroke-width="([^"]+)"', text):
        d, stroke, opacity, width = match.groups()
        parts = ["M" + part.strip() for part in d.split("M") if part.strip()]
        layers.append({"stroke": stroke, "opacity": float(opacity), "width": float(width), "paths": parts})
    if not layers:
        raise SystemExit(f"No contour paths found in {svg}")
    out.write_text(
        "// Generated by showreel/prepare.py from app/web/img/bg-topo.svg (1920x1200): its contours, split per line.\n"
        f"export const TOPO = {json.dumps(layers)};\n"
    )


if __name__ == "__main__":
    main()
